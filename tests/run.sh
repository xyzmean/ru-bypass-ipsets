#!/bin/sh
# Стенды репозитория. Ни один не требует сети: всё считается по схеме и по выпущенным
# файлам в lists/. Прогон — единицы секунд, поэтому шаг стоит в validate.yml, который
# срабатывает на каждый push в main (в том числе на автокоммит сборки).
set -e
cd "$(dirname "$0")/.."
fail=0
for t in tests/gate_shared_proxy.py; do
  echo "--- $t"
  python3 "$t" || fail=1
done
[ "$fail" = 0 ] && echo "все стенды зелёные" || echo "есть провалившиеся стенды"
exit $fail
