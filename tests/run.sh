#!/bin/sh
# Стенды репозитория. Ни один не требует сети: всё считается по схеме и по выпущенным
# файлам в lists/. Прогон — единицы секунд, поэтому шаг стоит в обоих workflow.
#
# Где именно они стоят и почему в двух местах. validate.yml запускается на push в main —
# то есть на коммитах человека; автокоммит сборки под secrets.GITHUB_TOKEN workflow не
# запускает вовсе, и до опубликованных списков этот прогон не доезжает (I-108). Поэтому
# те же стенды вызываются вторым местом — в resolve.yml перед шагом коммита, когда данные
# уже собраны и ещё не опубликованы. Там это гейт: красный стенд означает, что снапшот не
# публикуется и роутеры остаются на прошлом.
#
# Отсюда требование ко всему, что добавляется сюда: стенд обязан ловить либо то, ошибка в
# чём портит МАРШРУТИЗАЦИЮ выпущенных данных, либо поломку самой страховки (гейта, режима
# --warn-only) — второе доезжает сюда с коммитом человека и до публикующей сборки.
# Расхождение в метаданных сторожит selfcheck.py --warn-only аннотациями: уронить
# публикацию из-за описания дороже, чем оставить описание кривым.
set -e
cd "$(dirname "$0")/.."
fail=0
for t in tests/gate_list_format.py tests/gate_shared_proxy.py tests/gate_resolve_volume.py tests/gate_category_coverage.py tests/gate_release_assets.py tests/precheck_states.py tests/asn_pull_states.py tests/selfcheck_warn_only.py; do
  echo "--- $t"
  python3 "$t" || fail=1
done
[ "$fail" = 0 ] && echo "все стенды зелёные" || echo "есть провалившиеся стенды"
exit $fail
